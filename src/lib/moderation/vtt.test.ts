import { describe, expect, it } from "vitest";
import { vttToText } from "./vtt";

describe("vttToText", () => {
  it("keeps only the spoken words", () => {
    const vtt = `WEBVTT
Kind: captions
Language: en

NOTE generated by Stream

1
00:00:00.000 --> 00:00:02.500
When my son was born,

2
00:00:02.500 --> 00:00:05.000 align:start
<v Speaker>I had no idea what I was doing.</v>
`;
    expect(vttToText(vtt)).toBe("When my son was born, I had no idea what I was doing.");
  });

  it("collapses rolling-caption repeats and decodes entities", () => {
    const vtt = "WEBVTT\n\n00:01.000 --> 00:02.000\nTom &amp; me\n\n00:02.000 --> 00:03.000\nTom &amp; me\n\n00:03.000 --> 00:04.000\n<i>went fishing</i>\n";
    expect(vttToText(vtt)).toBe("Tom & me went fishing");
  });

  it("handles Windows line endings and empty files", () => {
    expect(vttToText("WEBVTT\r\n\r\n00:00.000 --> 00:01.000\r\nHello\r\n")).toBe("Hello");
    expect(vttToText("WEBVTT\n")).toBe("");
  });
});
